#!/usr/bin/env python3

a = int(input("Give me the first number: "))
b = int(input("Give me the second number: "))

print("Thank you!")
print(str(a) + " + " + str(b) + " = " + str(a + b))
print(str(a) + " - " + str(b) + " = " + str(a - b))
print(str(a) + " / " + str(b) + " = " + str(int(a / b)))
print(str(a) + " * " + str(b) + " = " + str(a * b))
